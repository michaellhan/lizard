// Synthetic poker-table screenshots and the card reader's glyph templates, drawn in Chromium (Playwright's, the one the
// browser tests use). Nothing here comes from a real poker room: the tables are HTML drawn by this script, in fonts this
// Mac has, so the screenshot reader can be tested and measured without images Lizard can't license.
//
//   node scripts/screenshot/make-fixtures.mjs templates        -> web/src/features/analyze/screenshot/templates.ts
//   node scripts/screenshot/make-fixtures.mjs fixtures         -> the committed fixtures (screenshot/fixtures/)
//   node scripts/screenshot/make-fixtures.mjs sweep DIR N      -> N more tables in DIR (not committed), for the
//                                                                 accuracy sweep (LIZARD_SHOT_DIR=DIR npx vitest run ...)
//
// The templates are drawn in TEMPLATE_FONTS only; the tables use those and HELD_OUT_FONTS (and suit shapes drawn as SVG
// paths, which no template has), and truth.json says which, so accuracy is reported on unseen fonts too.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";
import { encodeGrid, GRID_H, GRID_W, toGrid } from "../../web/src/features/analyze/screenshot/glyph.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const SHOT = join(root, "web", "src", "features", "analyze", "screenshot");

const TEMPLATE_FONTS = ["Arial", "Helvetica", "Times New Roman", "Verdana", "Tahoma", "Courier New"];
const HELD_OUT_FONTS = ["Georgia", "Trebuchet MS", "Futura", "Gill Sans", "Avenir Next", "Optima"];
const SUIT_FONTS = ["Arial", "Times New Roman", "Apple Symbols", "Menlo", "Verdana"];
const RANKS = ["A", "K", "Q", "J", "10", "T", "9", "8", "7", "6", "5", "4", "3", "2"];
const SUITS = { s: "♠", h: "♥", d: "♦", c: "♣" };
const VS15 = "︎"; // (text presentation: never the emoji)

// ---- a seeded random stream (mulberry32), so a run draws the same tables
function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const pick = (r, xs) => xs[Math.floor(r() * xs.length)];

// ---- templates: each glyph drawn big on a canvas, its alpha as coverage, cut to its box and gridded by glyph.ts
async function makeTemplates(page) {
  const jobs = [];
  // (a 10 also drawn tight, its digits touching, as rooms often draw it)
  for (const f of TEMPLATE_FONTS)
    for (const w of ["700", "400"])
      for (const r of RANKS)
        for (const ls of r === "10" ? ["0px", "-5px", "-10px"] : ["0px"]) jobs.push({ kind: "rank", label: r === "10" ? "T" : r, text: r, font: `${w} 96px "${f}"`, ls });
  for (const f of SUIT_FONTS) for (const [k, ch] of Object.entries(SUITS)) jobs.push({ kind: "suit", label: k, text: ch + VS15, font: `400 96px "${f}"` });
  for (const f of TEMPLATE_FONTS) jobs.push({ kind: "dealer", label: "D", text: "D", font: `700 96px "${f}"` });
  const drawn = await page.evaluate((jobs) => {
    const c = document.createElement("canvas");
    c.width = 260;
    c.height = 160;
    const g = c.getContext("2d", { willReadFrequently: true });
    return jobs.map((j) => {
      g.clearRect(0, 0, c.width, c.height);
      g.font = j.font;
      g.letterSpacing = j.ls ?? "0px";
      g.fillStyle = "#000";
      g.textBaseline = "middle";
      g.fillText(j.text, 20, 80);
      const a = g.getImageData(0, 0, c.width, c.height).data;
      const cov = new Array(c.width * c.height);
      for (let i = 0; i < cov.length; i++) cov[i] = a[i * 4 + 3] / 255;
      return { ...j, w: c.width, h: c.height, cov };
    });
  }, jobs);
  const out = [];
  const seen = new Set();
  for (const d of drawn) {
    let x0 = d.w, y0 = d.h, x1 = -1, y1 = -1;
    for (let y = 0; y < d.h; y++)
      for (let x = 0; x < d.w; x++)
        if (d.cov[y * d.w + x] >= 0.4) {
          if (x < x0) x0 = x;
          if (x > x1) x1 = x;
          if (y < y0) y0 = y;
          if (y > y1) y1 = y;
        }
    if (x1 < 0) continue;
    const box = { x: x0, y: y0, w: x1 - x0 + 1, h: y1 - y0 + 1 };
    const bits = encodeGrid(toGrid(d.cov, d.w, box));
    const key = `${d.kind}${d.label}${bits}`;
    if (seen.has(key)) continue; // (a font this Mac lacks falls back to one already drawn)
    seen.add(key);
    out.push({ kind: d.kind, label: d.label, aspect: +(box.w / box.h).toFixed(3), bits, from: d.font.replace(/ 96px/, "") });
  }
  const lines = out.map((t) => `  { kind: "${t.kind}", label: "${t.label}", aspect: ${t.aspect}, bits: "${t.bits}" }, // ${t.from}`);
  const ts = `// Generated by scripts/screenshot/make-fixtures.mjs templates: do not edit. Glyphs drawn on a canvas in Chromium
// (${TEMPLATE_FONTS.join(", ")}; suits also in ${SUIT_FONTS.filter((f) => !TEMPLATE_FONTS.includes(f)).join(", ")}), each its
// ink's coverage on a ${GRID_W}×${GRID_H} grid (glyph.ts). Ranks are labelled as Lizard writes them (10 is T).

export interface Template {
  kind: "rank" | "suit" | "dealer";
  label: string;
  /** the glyph's width over its height */
  aspect: number;
  bits: string;
}

export const TEMPLATES: readonly Template[] = [
${lines.join("\n")}
];
`;
  writeFileSync(join(SHOT, "templates.ts"), ts);
  console.log(`templates.ts: ${out.length} templates`);
}

// ---- tables
const NAMES = ["Kestrel", "fish_77", "NitPicker", "RiverRat", "ace_hi", "Moose", "Lumen", "vbet", "Quokka", "tilt42", "Sable", "Orca"];
const POSITIONS = {
  2: ["SB", "BB"],
  3: ["BTN", "SB", "BB"],
  4: ["CO", "BTN", "SB", "BB"],
  5: ["HJ", "CO", "BTN", "SB", "BB"],
  6: ["UTG", "HJ", "CO", "BTN", "SB", "BB"],
  7: ["UTG", "LJ", "HJ", "CO", "BTN", "SB", "BB"],
  8: ["UTG", "UTG1", "LJ", "HJ", "CO", "BTN", "SB", "BB"],
  9: ["UTG", "UTG1", "UTG2", "LJ", "HJ", "CO", "BTN", "SB", "BB"],
};

/** Each seat's position, seats numbered clockwise from the hero's (0), with the button at seat `d`. */
function positionsOf(n, d) {
  const others = POSITIONS[n].filter((p) => p !== "SB" && p !== "BB");
  const order = n === 2 ? ["BB", "SB"] : ["SB", "BB", ...others]; // clockwise from the seat after the button
  const out = new Array(n);
  for (let k = 0; k < n; k++) out[(d + 1 + k) % n] = order[k];
  return out;
}

const STYLES = ["classic", "four-ink", "four-face", "big-index"];
const FELTS = [
  ["#1f6f43", "#0f3d24", "#2a1a10"],
  ["#1d4f8a", "#0e2a4d", "#1a1a1a"],
  ["#3b3f45", "#1f2226", "#0b0c0e"],
  ["#7a1f2b", "#3d0f16", "#1a1010"],
];
const STAKES = [
  [0.5, 1, "$"],
  [1, 2, "$"],
  [0.25, 0.5, "$"],
  [50, 100, ""],
  [100, 200, ""],
  [2, 5, "€"],
];

function money(v, cur, r) {
  const fixed = cur && v % 1 ? v.toFixed(2) : String(v);
  const [i, f] = fixed.split(".");
  const grouped = r() < 0.6 ? i.replace(/\B(?=(\d{3})+(?!\d))/g, ",") : i;
  return `${cur}${grouped}${f ? `.${f}` : ""}`;
}

function drawDeck(r) {
  const deck = [];
  for (const rk of "AKQJT98765432") for (const s of "shdc") deck.push(rk + s);
  for (let i = deck.length - 1; i > 0; i--) {
    const j = Math.floor(r() * (i + 1));
    [deck[i], deck[j]] = [deck[j], deck[i]];
  }
  return deck;
}

/** One table's description: everything the page draws and everything the reader should find. */
function makeTable(seed, opts = {}) {
  const r = rng(seed);
  const n = opts.players ?? pick(r, [2, 3, 6, 6, 6, 9, 9, 4, 5, 8]);
  const heldOut = opts.heldOut ?? r() < 0.5;
  const font = pick(r, heldOut ? HELD_OUT_FONTS : TEMPLATE_FONTS);
  const style = opts.style ?? pick(r, STYLES);
  const svgSuits = opts.svgSuits ?? (heldOut && r() < 0.5);
  const [W, H] = pick(r, [[960, 600], [1100, 690], [880, 560], [1280, 800]]);
  const felt = pick(r, FELTS);
  const [sb, bb, cur] = pick(r, STAKES);
  const inBB = r() < 0.25;
  const boardN = opts.board ?? pick(r, [0, 3, 3, 4, 5, 5]);
  const deck = drawDeck(r);
  const hero = [deck.pop(), deck.pop()];
  const board = Array.from({ length: boardN }, () => deck.pop());
  const d = Math.floor(r() * n);
  const pos = positionsOf(n, d);
  const shown = n > 2 && boardN === 5 && r() < 0.4 ? 1 + Math.floor(r() * (n - 1)) : -1;
  const villain = shown >= 0 ? [deck.pop(), deck.pop()] : null;
  const stacksBB = Array.from({ length: n }, () => Math.round((20 + r() * 230) * 2) / 2);
  const potBB = boardN ? Math.round((5 + r() * 60) * 2) / 2 : Math.round((1.5 + r() * 8) * 2) / 2;
  const fmt = (vbb) => (inBB ? `${vbb} BB` : money(Math.round(vbb * bb * 100) / 100, cur, r));
  const header = inBB
    ? pick(r, [`NL Hold'em ${cur}${sb}/${cur}${bb}`, `Blinds ${cur}${sb}/${cur}${bb}`])
    : pick(r, [`NL Hold'em ${cur}${sb}/${cur}${bb}`, `Blinds ${cur}${sb}/${cur}${bb}`, `No Limit Hold'em - ${cur}${sb}/${cur}${bb}`]);
  const potLabel = pick(r, ["Pot: ", "Total pot: ", "POT "]);
  const tenSpacing = -0.1 * r(); // (how tight a 10's two digits sit, in em)
  return {
    seed,
    tenSpacing,
    W,
    H,
    n,
    font,
    heldOut,
    style,
    svgSuits,
    felt,
    overlap: r() < 0.5,
    cardScale: 0.85 + r() * 0.5,
    header,
    potText: potLabel + fmt(potBB),
    seats: Array.from({ length: n }, (_, i) => ({ name: i === 0 ? "Hero" : pick(r, NAMES), stack: fmt(stacksBB[i]), pos: pos[i] })),
    dealer: d,
    hero,
    board,
    shown,
    villain,
    truth: {
      players: n,
      heroPos: pos[0],
      hero: hero.join(""),
      board: board.join(""),
      sb,
      bb,
      unit: inBB ? "bb" : "money",
      pot: inBB ? potBB : Math.round(potBB * bb * 100) / 100,
      stacks: Object.fromEntries(pos.map((p, i) => [p, inBB ? stacksBB[i] : Math.round(stacksBB[i] * bb * 100) / 100])),
      style,
      font,
      heldOut,
      svgSuits,
    },
  };
}

// The page that draws a table (runs in the browser).
function drawTable(t) {
  const SUIT_CH = { s: "♠︎", h: "♥︎", d: "♦︎", c: "♣︎" };
  // (shapes no template has: drawn as paths, for the held-out half)
  const SUIT_PATH = {
    s: "M50 5 C35 30 5 45 5 65 C5 82 25 90 42 78 L35 98 L65 98 L58 78 C75 90 95 82 95 65 C95 45 65 30 50 5Z",
    h: "M50 95 C30 75 3 58 3 33 C3 15 18 4 32 4 C42 4 48 12 50 18 C52 12 58 4 68 4 C82 4 97 15 97 33 C97 58 70 75 50 95Z",
    d: "M50 2 L88 50 L50 98 L12 50Z",
    c: "M50 4 A20 20 0 1 1 49.9 4Z M24 38 A20 20 0 1 1 23.9 38Z M76 38 A20 20 0 1 1 75.9 38Z M44 50 L56 50 L64 98 L36 98Z",
  };
  const two = { s: "#111", h: "#d01818", d: "#d01818", c: "#111" };
  const four = { s: "#111", h: "#d01818", d: "#1a5fd0", c: "#168a2e" };
  const face = { s: "#2b2b2b", h: "#c62828", d: "#1565c0", c: "#2e7d32" };
  document.body.style.cssText = `margin:0;width:${t.W}px;height:${t.H}px;background:${t.felt[2]};position:relative;overflow:hidden;font-family:"${t.font}",sans-serif`;
  const el = (tag, css, html = "") => {
    const e = document.createElement(tag);
    e.style.cssText = css;
    e.innerHTML = html;
    document.body.appendChild(e);
    return e;
  };
  const cx = t.W / 2, cy = t.H * 0.47, rx = t.W * 0.36, ry = t.H * 0.3;
  el("div", `position:absolute;left:${cx - rx - 14}px;top:${cy - ry - 14}px;width:${2 * rx + 28}px;height:${2 * ry + 28}px;border-radius:50%;background:#3a2a1a`);
  el("div", `position:absolute;left:${cx - rx}px;top:${cy - ry}px;width:${2 * rx}px;height:${2 * ry}px;border-radius:50%;background:${t.felt[0]};box-shadow:inset 0 0 0 10px ${t.felt[1]}`);
  el("div", `position:absolute;left:14px;top:10px;color:#e8e8e8;font-size:16px`, t.header);
  const ch = Math.round(Math.min(t.W, t.H * 1.6) * 0.085 * t.cardScale), cw = Math.round(ch * 0.71);
  const suitHtml = (s, size, color) =>
    t.svgSuits
      ? `<svg width="${size}" height="${size}" viewBox="0 0 100 100" style="display:block"><path d="${SUIT_PATH[s]}" fill="${color}"/></svg>`
      : `<span style="font-family:'${t.font}','Apple Symbols',sans-serif;font-size:${size}px;line-height:1;color:${color};display:block">${SUIT_CH[s]}</span>`;
  const card = (code, x, y, z) => {
    const rk = code[0] === "T" ? "10" : code[0], s = code[1];
    const colorful = t.style === "four-face";
    const ink = colorful ? "#fff" : (t.style === "classic" ? two : four)[s];
    const bg = colorful ? face[s] : "#fafafa";
    const big = t.style === "big-index";
    const rs = Math.round(ch * (big ? 0.4 : 0.3)), ss = Math.round(ch * (big ? 0.3 : 0.2));
    const c = el("div", `position:absolute;left:${x}px;top:${y}px;width:${cw}px;height:${ch}px;border-radius:${Math.round(ch * 0.07)}px;background:${bg};border:1px solid #777;box-sizing:border-box;z-index:${z};overflow:hidden`);
    c.innerHTML =
      `<div style="position:absolute;left:${Math.round(cw * 0.07)}px;top:${Math.round(ch * 0.04)}px;display:flex;flex-direction:column;align-items:center">` +
      `<span style="font-weight:700;font-size:${rs}px;line-height:1;color:${ink};letter-spacing:${rk === "10" ? t.tenSpacing * rs : 0}px">${rk}</span>` +
      `<div style="margin-top:${Math.round(ch * 0.02)}px">${suitHtml(s, ss, ink)}</div></div>` +
      (big || colorful ? "" : `<div style="position:absolute;right:${Math.round(cw * 0.1)}px;bottom:${Math.round(ch * 0.08)}px">${suitHtml(s, Math.round(ch * 0.42), ink)}</div>`);
  };
  // board and pot
  if (t.board.length) {
    const gap = Math.round(cw * 0.12), total = t.board.length * cw + (t.board.length - 1) * gap;
    t.board.forEach((c, i) => card(c, Math.round(cx - total / 2 + i * (cw + gap)), Math.round(cy - ch / 2), 1));
  }
  el("div", `position:absolute;left:0;width:${t.W}px;text-align:center;top:${Math.round(cy - ch / 2 - 34)}px;color:#f2f2f2;font-size:18px;font-weight:600`, t.potText);
  // seats, clockwise from the hero at the bottom
  const seatAt = (i) => {
    const a = Math.PI / 2 + (i * 2 * Math.PI) / t.n;
    return [cx + (rx + 30) * Math.cos(a), cy + (ry + 34) * Math.sin(a), a];
  };
  t.seats.forEach((s, i) => {
    const [x, y] = seatAt(i);
    const bw = 128, bh = 50;
    el("div", `position:absolute;left:${Math.round(x - bw / 2)}px;top:${Math.round(y - bh / 2)}px;width:${bw}px;height:${bh}px;border-radius:10px;background:#15181c;border:2px solid #4a4f57;color:#ddd;text-align:center;font-size:14px;line-height:22px;box-sizing:border-box;z-index:3`, `<div>${s.name}</div><div style="color:#fff;font-weight:700;font-size:15px">${s.stack}</div>`);
  });
  // the dealer button, between its seat and the middle
  {
    const [x, y] = seatAt(t.dealer);
    const bx = x + (x <= cx ? 84 : -84), by = y; // (beside the seat's box, clear of its cards)
    el("div", `position:absolute;left:${Math.round(bx - 13)}px;top:${Math.round(by - 13)}px;width:26px;height:26px;border-radius:50%;background:#f4f4f4;border:2px solid #999;box-sizing:border-box;color:#111;font:700 15px Arial;display:flex;align-items:center;justify-content:center;z-index:4`, "D");
  }
  // hole cards above their seats
  const hand = (cards, i) => {
    const [x, y, a] = seatAt(i);
    const step = t.overlap ? Math.round(cw * 0.55) : cw + 4;
    // (above the seat's box, or below it for a seat in the table's top half)
    const left = Math.round(x - (cw + step) / 2), top = Math.round(Math.sin(a) < -0.2 ? y + 25 + 6 : y - 25 - ch - 6);
    cards.forEach((c, k) => card(c, left + k * step, top, 5 + k));
  };
  hand(t.hero, 0);
  if (t.villain) hand(t.villain, t.shown);
}

async function renderTables(page, tables, dir) {
  mkdirSync(dir, { recursive: true });
  const truth = [];
  for (const [i, t] of tables.entries()) {
    await page.setViewportSize({ width: t.W, height: t.H });
    await page.setContent("<!doctype html><html><body></body></html>");
    await page.evaluate(drawTable, t);
    const file = `table-${String(i + 1).padStart(3, "0")}.png`;
    await page.screenshot({ path: join(dir, file), clip: { x: 0, y: 0, width: t.W, height: t.H } });
    truth.push({ file, ...t.truth });
  }
  writeFileSync(join(dir, "truth.json"), JSON.stringify(truth, null, 1) + "\n");
  console.log(`${tables.length} tables in ${dir}`);
}

const [cmd = "", a1, a2] = process.argv.slice(2);
const browser = await chromium.launch();
const page = await browser.newPage({ deviceScaleFactor: 1 });
try {
  if (cmd === "templates") await makeTemplates(page);
  else if (cmd === "fixtures") {
    // a small committed set covering each style, table size and board length, half in held-out fonts
    const tables = [];
    let k = 0;
    for (const style of STYLES)
      for (const heldOut of [false, true])
        for (const [players, board] of heldOut ? [[9, 5]] : [[6, 3], [2, 0]]) tables.push(makeTable(1000 + k++, { style, heldOut, players, board, svgSuits: heldOut && (style === "four-ink" || style === "big-index") }));
    await renderTables(page, tables, join(SHOT, "fixtures"));
  } else if (cmd === "sweep" && a1) {
    const n = Number(a2 ?? 100);
    await renderTables(page, Array.from({ length: n }, (_, i) => makeTable(50_000 + i)), a1);
  } else {
    console.error("usage: make-fixtures.mjs templates | fixtures | sweep DIR N");
    process.exitCode = 1;
  }
} finally {
  await browser.close();
}
