"""Lizard's flop valuation for the preflop game: upstream's library model (solver/gto/pf_game.LibraryModel, as Study's
class-level solve uses it) with a small set of corrections per pot type, calibrated against published solves.

A heads-up flop pays each player its realized share of the pot. pf_game.LibraryModel gives the aggressor's share
S[i, j] (its class i against the caller's class j) per spot from the flop library's per-class values; this module
moves it per pot type t (1 single-raised, 2 3bet, 3 4bet):

    S'[i, j] = eq[i, j] + k_t * (S[i, j] - eq[i, j]) + d_t,pos

k_t scales the excess over all-in equity (the postflop edge), and d_t,pos adds a constant share of the pot to the
aggressor (taken from the caller, so a pair's two shares still add to the pot), pos being whether the aggressor has
position. The library's river correction (advisor._river_fix, the hands that win when the river comes) keeps its
scale per pot type as `r1`/`r2`, and `ext` picks how classes outside a library spot's range are valued
(FeatureLibraryModel). The values come from engine/pf_calib.py (generated by scripts/pf/calibrate.py `write`); without
it, or with `Params()`, the model is exactly the library model Study's class-level solve uses (pf_study.flop_model).

Another stack depth keeps pf_study.DEPTH_SCALE on top: the excess (k_t's part included) times that depth's factor,
the shifts d unchanged.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, Optional

import numpy as np

from gto import pf_game as G
from gto.pf_classes import equity_matrix



@dataclass(frozen=True)
class Params:
    """The corrections (defaults: none, the library model as Study uses it)."""
    d1_ip: float = 0.0      # single-raised pot, aggressor in position: share of the pot moved to the aggressor
    d1_oop: float = 0.0     # ... aggressor out of position
    d2_ip: float = 0.0      # 3bet pot
    d2_oop: float = 0.0
    d3: float = 0.0         # 4bet pot (either position)
    k1: float = 1.0         # scale of the excess over equity, single-raised pots
    k2: float = 1.0         # 3bet pots
    k3: float = 1.0         # 4bet pots
    r1: float = 1.0         # advisor._river_fix's scale in single-raised pots (pf_study.RIVER_FIX[0])
    r2: float = 0.5         # ... in 3bet pots (pf_study.RIVER_FIX[1])
    ext: float = 0.0        # classes outside a library spot's range: 0 upstream's (the measured model joined at the
                            # range's edge), 1 a smooth fit on hand shape of the range's own library values

    NAMES = ("d1_ip", "d1_oop", "d2_ip", "d2_oop", "d3", "k1", "k2", "k3", "r1", "r2", "ext")

    def vector(self) -> np.ndarray:
        return np.array([getattr(self, n) for n in self.NAMES], float)

    @classmethod
    def of(cls, v) -> "Params":
        if isinstance(v, dict):
            return cls(**{k: float(x) for k, x in v.items() if k in cls.NAMES})
        return cls(**{n: float(x) for n, x in zip(cls.NAMES, v)})

    def as_dict(self) -> Dict[str, float]:
        return {n: round(float(getattr(self, n)), 6) for n in self.NAMES}


def load_params() -> Optional[Params]:
    """The calibrated corrections (engine/pf_calib.py's PARAMS), or None without it."""
    try:
        from . import pf_calib
    except ImportError:
        return None
    return Params.of(pf_calib.PARAMS)


def shape_features(e: np.ndarray) -> np.ndarray:
    """(K, F): per class its equity against the opponent's range (e, centred) and hand shape, for the extrapolation."""
    pair, suited, conn, gap, high = G.class_shape()
    from gto.pf_classes import CLASSES
    rk = "23456789TJQKA"
    low = np.array([rk.index(c[1]) / 12.0 for c in CLASSES]) * (1 - pair)
    x = e - 0.5
    return np.stack([np.ones_like(x), x, x * np.abs(x), pair, suited, conn, gap, high, low, pair * x, suited * x,
                     conn * x, high * x], 1)


def _shape_of():
    from gto.pf_classes import CLASSES
    rk = "23456789TJQKA"
    kind = np.array([0 if len(c) == 2 else 1 if c[2] == "s" else 2 for c in CLASSES])
    hi = np.array([rk.index(c[0]) for c in CLASSES])
    lo = np.array([rk.index(c[1]) for c in CLASSES])
    return kind, hi, lo


def feature_excess(excess: np.ndarray, e: np.ndarray, w: np.ndarray, ridge: float = 1e-3) -> np.ndarray:
    """Every class's excess share over equity from the classes where w > 0 (their own values there): a class outside
    takes its nearest neighbour's of the same kind (pair, suited, offsuit; the same high card where one is in, then the
    nearest low card), moved by the difference between the two in a smooth fit on shape_features (weighted by w)."""
    X = shape_features(e)
    m = w > 0
    W = w[m] / w[m].sum()
    A = X[m].T @ (X[m] * W[:, None]) + ridge * np.eye(X.shape[1])
    fit = X @ np.linalg.solve(A, X[m].T @ (W * excess[m]))
    kind, hi, lo = _shape_of()
    out = np.where(m, excess, fit)
    idx = np.nonzero(m)[0]
    for i in np.nonzero(~m)[0]:
        same = idx[kind[idx] == kind[i]]
        if len(same) == 0:
            continue
        d = 3 * np.abs(hi[same] - hi[i]) + np.abs(lo[same] - lo[i]) if kind[i] else np.abs(hi[same] - hi[i])
        j = same[np.argmin(d)]
        out[i] = excess[j] + fit[i] - fit[j]
    return out


class FeatureLibraryModel(G.LibraryModel):
    """pf_game.LibraryModel with the classes outside a spot's range valued by a smooth fit (feature_excess) of the
    range's own library values on hand shape and equity, in place of the measured model (pf_eqr) shifted at the
    range's edge: the library's 552-1755 flops a spot decide every class, and a class just outside the range is
    valued like its neighbours inside it (upstream's join put A2o above A4o on the button)."""

    def _fit(self, k: tuple) -> np.ndarray:
        sid, v = self.spots[k]
        eq = equity_matrix()
        from gto.pf_classes import PAIR_COMPAT
        aggr_side = "ip" if k[1] else "oop"
        call_side = "oop" if k[1] else "ip"
        ma, mc = np.asarray(v[aggr_side]["share"]), np.asarray(v[call_side]["share"])
        ra, rc = np.asarray(v[aggr_side]["range"], float), np.asarray(v[call_side]["range"], float)
        ina, inc = np.asarray(v[aggr_side]["w"]) > 0, np.asarray(v[call_side]["w"]) > 0
        P = PAIR_COMPAT * rc[None, :]
        Q = PAIR_COMPAT * ra[:, None]
        Pn = P / np.maximum(P.sum(1, keepdims=True), 1e-12)
        Qn = Q / np.maximum(Q.sum(0, keepdims=True), 1e-12)
        ea = (Pn * eq).sum(1)
        ec = (Qn * (1 - eq)).sum(0)
        if self.river_fix is not None:
            sc = self.river_scale.get(k[0], 0.0)
            ma = ma + sc * self.river_fix * ea
            mc = mc + sc * self.river_fix * ec
        from gto.pf_classes import N_IN
        xa_m = feature_excess(ma - ea, ea, ra * ina * N_IN)
        xc_m = feature_excess(mc - ec, ec, rc * inc * N_IN)
        a = np.where(ina, ma - ea, xa_m)
        c = np.zeros(len(a))
        with np.errstate(all="ignore"):
            a, c, da, dc = self._solve_ac(a, c, ma, mc, ea, ec, xa_m, xc_m, Pn, Qn, ra, rc, ina, inc)
        S = np.clip(eq + a[:, None] - c[None, :], -3.0, 4.0)
        fa, fc = (Pn * S).sum(1), (Qn * (1 - S)).sum(0)
        self.fit_info[sid] = {"key": k, "edge_aggr": da, "edge_caller": dc,
                              "realize_aggr": float((ra * ina * fa).sum() / max((ra * ina * ea).sum(), 1e-12)),
                              "realize_caller": float((rc * inc * fc).sum() / max((rc * inc * ec).sum(), 1e-12))}
        return S


class CalibratedModel(G.EQRModel):
    """pf_game.LibraryModel's shares with Params' corrections (the module's doc) and pf_study's depth scale."""
    by_spot = True

    def __init__(self, params: Params = Params(), depth_scale: Optional[Dict[int, float]] = None):
        super().__init__(share_fn=self._pick)
        from gto.advisor import _river_fix
        self.params = params
        self.depth = depth_scale or {}
        cls = FeatureLibraryModel if params.ext >= 0.5 else G.LibraryModel
        self.lib = cls(river_fix=_river_fix(), river_scale={1: params.r1, 2: params.r2})

    def _pick(self, key):
        S = self.lib.share(key if len(key) >= 4 else key[:2] + ("", ""))
        t = int(key[0])
        p = self.params
        k = {1: p.k1, 2: p.k2, 3: p.k3}.get(t, 1.0) * self.depth.get(t, 1.0)
        d = {1: p.d1_ip if key[1] else p.d1_oop, 2: p.d2_ip if key[1] else p.d2_oop, 3: p.d3}.get(t, 0.0)
        if k == 1.0 and d == 0.0:
            return S
        eq = equity_matrix()
        return np.clip(eq + k * (S - eq) + d, -3.0, 4.0)


def flop_model(stack: float, params: Optional[Params] = None) -> CalibratedModel:
    """The calibrated model at a stack depth (pf_study.depth_scale's factors), params default engine/pf_calib.py's."""
    from gto.pf_study import depth_scale
    return CalibratedModel(params if params is not None else (load_params() or Params()), depth_scale(stack))
