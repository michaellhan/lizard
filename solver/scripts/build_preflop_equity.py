"""Build gto/pf_equity.py: all-in preflop equity between the 169 hand classes (averaged over the
combo pairs that don't share a card), sampled over random boards. Used by the push/fold
equilibrium for short-stack jams.

    .venv/bin/python scripts/build_preflop_equity.py [boards]
    .venv/bin/python scripts/build_preflop_equity.py exact

Lizard: `exact` enumerates every board instead of sampling (each of the 134,459 boards distinct up to
a relabelling of the suits once, weighted by how many boards it stands for; a class pair's sum is the
same on every relabelling, since a relabelling maps each class onto itself). ~7 minutes, ~0.3 GB.
"""
import base64
import itertools
import os
import random
import sys
import zlib
import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from gto.evaluator import eval_board, eval_boards       # noqa: E402
from gto.pf_classes import COMPAT, class_sums             # noqa: E402

EXACT = len(sys.argv) > 1 and sys.argv[1] == "exact"
den = class_sums(COMPAT.astype(float))
if EXACT:
    allb = np.array(list(itertools.combinations(range(52), 5)), dtype=np.int8)
    r, su = allb.astype(np.int64) // 4, allb.astype(np.int64) % 4
    key = None
    for p in itertools.permutations(range(4)):
        mask = np.bitwise_or.reduce(np.int64(1) << (r * 4 + np.array(p)[su]), axis=1)
        key = mask if key is None else np.minimum(key, mask)
    _, first, mult = np.unique(key, return_index=True, return_counts=True)
    boards = allb[first].astype(np.int64)
    del allb, r, su, key
    assert mult.sum() == 2598960
    acc = np.zeros((1326, 1326), dtype=np.int64)      # sum over boards of sign(strength gap), both combos live
    cnt = np.zeros((1326, 1326), dtype=np.int64)      # boards on which both combos are live
    for lo in range(0, len(boards), 1000):
        S = eval_boards(boards[lo:lo + 1000])
        for k in range(len(S)):
            v = S[k]
            m = int(mult[lo + k])
            d = np.sign(v[:, None] - v[None, :]).astype(np.int64)
            live = v >= 0
            d[~live] = 0
            d[:, ~live] = 0
            acc += m * d
            cnt += m * (live[:, None] & live[None, :])
        print(lo, file=sys.stderr)
    # a single combo pair's sums depend on which board stands for its relabellings; a class pair's don't. Over every
    # board, each pair of combos that don't share a card is live on exactly C(48, 5) of them.
    assert np.array_equal(class_sums(cnt * COMPAT), den * 1712304)
    num = 0.5 * den + class_sums(acc * COMPAT) / (2.0 * 1712304)
    n_boards = "every board, exactly"
else:
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 3000
    rng = random.Random(7)
    win2 = np.zeros((1326, 1326), dtype=np.int32)   # 2 per win, 1 per tie
    cnt = np.zeros((1326, 1326), dtype=np.int32)
    for i in range(n):
        s = eval_board(rng.sample(range(52), 5))
        ok = s >= 0
        live = ok[:, None] & ok[None, :]
        win2 += live * ((s[:, None] > s[None, :]) * 2 + (s[:, None] == s[None, :]))
        cnt += live
        if i % 500 == 0:
            print(i, file=sys.stderr)
    eq = np.where(cnt > 0, win2 / np.maximum(2 * cnt, 1), 0.0)
    n_boards = f"{n} random boards"
    num = class_sums(eq * COMPAT)
m = np.where(den > 0, num / np.maximum(den, 1), 0.5)
blob = base64.b64encode(zlib.compress(np.round(m * 65535).astype("<u2").tobytes(), 9)).decode()
out = os.path.join(os.path.dirname(__file__), "..", "gto", "pf_equity.py")
with open(out, "w") as f:
    f.write('"""Generated by scripts/build_preflop_equity.py: all-in preflop equity between the hand\n'
            f'classes in gto.pf_classes.CLASSES order ({n_boards}), uint16 / 65535."""\n')
    f.write("DATA = (\n")
    for j in range(0, len(blob), 96):
        f.write(f'    "{blob[j:j + 96]}"\n')
    f.write(")\n")
print("wrote", out, len(blob), "chars")
